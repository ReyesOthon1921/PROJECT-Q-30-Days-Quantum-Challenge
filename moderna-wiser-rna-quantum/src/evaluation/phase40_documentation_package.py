            "",
            "`z_i in {-1, +1}`",
            "",
            "The Ising form is:",
            "",
            "`H_I(z) = C + sum_i h_i z_i + sum_{i<j} J_ij z_i z_j`",
            "",
            "with:",
            "",
            "`J_ij = b_ij / 4`",
            "",
            "`h_i = -a_i / 2 - (1/4) * sum_{j != i} b_ij`",
            "",
